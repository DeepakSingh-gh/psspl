import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import nodemailer from 'nodemailer';
import {createHash} from 'node:crypto';

test('SMTP queue encrypts links, retries safe failures, holds ambiguous outcomes, pins providers and rechecks local URL policy', async () => {
  const scratch=mkdtempSync(join(tmpdir(),'psspl-smtp-queue-'));
  Object.assign(process.env,{NODE_ENV:'test',CRM_DATABASE_PATH:join(scratch,'synthetic.sqlite'),CRM_DISABLE_BASELINE_RESTORE:'true',CRM_EMAIL_PROVIDER:'smtp',SMTP_HOST:'smtp.gmail.com',SMTP_PORT:'465',SMTP_SECURE:'true',SMTP_USER:'tester@gmail.com',SMTP_PASS:'synthetic-secret',EMAIL_FROM:'tester@gmail.com',APP_BASE_URL:'http://crm.example.test',CRM_EMAIL_QUEUE_KEY:'7'.repeat(64)});
  const {db}=await import('../server/db.mjs');
  const {queueAccountToken,issueAccountToken}=await import('../server/auth-tokens.mjs');
  const {processAuthEmailQueue}=await import('../server/auth-email-queue.mjs');
  const originalTransport=nodemailer.createTransport;
  let attempts=0, failure=null, lastMail;
  nodemailer.createTransport=()=>({async sendMail(mail){attempts++;lastMail=mail;if(failure)throw failure;return {accepted:[mail.to],messageId:`synthetic-${attempts}`};},close(){}});
  const add=id=>{db.prepare('INSERT INTO users(id,email,password_hash,role,active) VALUES(?,?,?,?,1)').run(id,`${id}@example.test`,'synthetic','salesperson');return {id,email:`${id}@example.test`};};
  const job=id=>db.prepare('SELECT * FROM auth_email_queue WHERE id=?').get(id);
  const delivery=id=>db.prepare('SELECT status FROM auth_email_delivery WHERE id=?').get(id)?.status;
  try {
    const user=add('retry'); const queued=queueAccountToken(user,'reset',{accountEmail:true});
    assert.ok(!job(queued.queueId).encrypted_payload.includes('token=')); assert.equal(job(queued.queueId).provider,'smtp');
    failure={code:'EMESSAGE',responseCode:451}; await processAuthEmailQueue();
    assert.equal(job(queued.queueId).status,'queued');assert.equal(job(queued.queueId).attempts,1);
    db.prepare("UPDATE auth_email_queue SET next_attempt_at='2000-01-01' WHERE id=?").run(queued.queueId);
    failure=null; await processAuthEmailQueue();
    assert.equal(job(queued.queueId).status,'accepted');assert.equal(delivery(queued.queueId),'accepted');assert.equal(job(queued.queueId).encrypted_payload,'');
    const unknown=queueAccountToken(add('unknown'),'reset');failure={code:'ETIMEDOUT',command:'DATA'}; await processAuthEmailQueue();
    assert.equal(delivery(unknown.queueId),'unknown');assert.equal(job(unknown.queueId).status,'failed');
    const issued=await issueAccountToken(add('issued-unknown'),'reset');
    assert.equal(issued.deliveryStatus,'unknown');assert.equal(issued.sent,false);
    const before=attempts;await processAuthEmailQueue();assert.equal(attempts,before);
    const crash=queueAccountToken(add('crash'),'reset');
    db.prepare("UPDATE auth_email_queue SET status='processing',lease_until='2000-01-01' WHERE id=?").run(crash.queueId);
    await processAuthEmailQueue();assert.equal(delivery(crash.queueId),'unknown');assert.equal(attempts,before);
    const switched=queueAccountToken(add('switched'),'reset');
    process.env.CRM_EMAIL_PROVIDER='resend';process.env.RESEND_API_KEY='synthetic';
    await processAuthEmailQueue();assert.equal(job(switched.queueId).status,'queued');
    process.env.CRM_EMAIL_PROVIDER='smtp';failure=null;await processAuthEmailQueue();assert.equal(job(switched.queueId).status,'accepted');
    process.env.APP_BASE_URL='http://localhost:3000';
    assert.equal(queueAccountToken(add('remote'),'reset').reason,'local_link_restricted');
    process.env.CRM_EMAIL_LOCAL_TEST_RECIPIENT='local@example.test';
    const local=queueAccountToken(add('local'),'reset');assert.equal(local.deliveryStatus,'queued');
    process.env.CRM_EMAIL_LOCAL_TEST_RECIPIENT='different@example.test';
    const last=attempts;await processAuthEmailQueue();assert.equal(attempts,last);assert.equal(job(local.queueId).last_error,'local_link_restricted');
    const remote=add('account-notice');
    const tokenCount=db.prepare('SELECT COUNT(*) n FROM auth_tokens').get().n;
    const notice=await issueAccountToken(remote,'reset',{accountEmail:true});
    assert.equal(notice.sent,true);assert.equal(notice.setupLinkIncluded,false);assert.equal(notice.deliveryStatus,'accepted');
    assert.ok(lastMail.text.includes('Login ID:'));
    assert.ok(!/localhost|127\.0\.0\.1|token=|https?:\/\//.test(lastMail.text));
    assert.equal(db.prepare('SELECT COUNT(*) n FROM auth_tokens').get().n,tokenCount,'notice does not create or invalidate reset tokens');
    const duplicate=await issueAccountToken(remote,'reset',{accountEmail:true});
    assert.equal(duplicate.reason,'cooldown');assert.equal(duplicate.previousDeliveryStatus,'accepted');
    const noticeRow=db.prepare("SELECT * FROM auth_email_queue WHERE user_id=? AND purpose='account'").get(remote.id);
    assert.equal(noticeRow.encrypted_payload,'');assert.equal(delivery(noticeRow.id),'accepted');
    const staleUser=add('stale-credentials');
    const stale=queueAccountToken(staleUser,'reset',{accountEmail:true,initialPassword:'Synthetic-Password-2026!',credentialVersion:createHash('sha256').update('synthetic').digest('hex')});
    assert.ok(!job(stale.queueId).encrypted_payload.includes('Synthetic-Password-2026!'));
    db.prepare("UPDATE users SET password_hash='replaced-hash' WHERE id=?").run(staleUser.id);
    const attemptsBeforeStale=attempts;await processAuthEmailQueue();
    assert.equal(attempts,attemptsBeforeStale);assert.equal(job(stale.queueId).last_error,'password_changed');
    assert.equal(job(stale.queueId).encrypted_payload,'');
    assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
  } finally {nodemailer.createTransport=originalTransport;db.close();rmSync(scratch,{recursive:true,force:true});}
});
