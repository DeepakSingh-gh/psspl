import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { finalReportFixture } from './fixtures/rm-report-finalization.mjs';

test('top sales cards preserve period scope, responsive alignment and dashboard/PDF values', {timeout:180000}, async()=>{
  const browser=await chromium.launch({headless:true});
  mkdirSync('scratch/rm-top-sales',{recursive:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(()=>localStorage.setItem('psspl_crm_session','fixture-admin'));
    await page.route('**/api/**',route=>{
      const url=new URL(route.request().url());
      if(url.pathname==='/api/auth/me')return route.fulfill({json:{user:{id:'fixture-admin',role:'admin',email:'fixture@example.test'}}});
      if(url.searchParams.get('reportVersion')!=='2')return route.fulfill({json:{}});
      const report=finalReportFixture(Object.fromEntries(url.searchParams));
      const rows=kind=>[.3,.25,.2,.1,.05].map((share,index)=>({id:`${kind}-${index}`,name:`Test ${kind} ${index+1}${index===0?' with a very long recorded business name for alignment verification':''}`,salesValue:report.summary.actual*share,sharePercent:share*100}));
      report.topSales={totalSales:report.summary.actual,customers:rows('customer'),products:rows('product'),productVariance:0};
      if(url.searchParams.get('financialYear')==='2023-24')report.topSales={totalSales:null,customers:[],products:[],reason:'No authoritative Tally invoice evidence exists for this reporting period.'};
      return route.fulfill({json:report});
    });
    await page.goto('http://localhost:3000/admin/team/raiskhan?fy=2026-27');
    const cards=page.locator('.rm-v2 [data-top-sales]');
    await cards.first().locator('tbody tr').first().waitFor();
    const values=()=>cards.evaluateAll(elements=>elements.map(el=>[...el.querySelectorAll('tbody tr')].map(row=>row.textContent)));
    const yearly=await values();
    assert.equal(await cards.count(),2);assert.equal(await cards.first().locator('tbody tr').count(),5);
    const boxes=await cards.evaluateAll(elements=>elements.map(el=>{const r=el.getBoundingClientRect();return {top:r.top,height:r.height}}));
    assert.equal(boxes[0].top,boxes[1].top);assert.equal(boxes[0].height,boxes[1].height);
    await page.locator('.rm-v2 [data-report-section=top-sales]').screenshot({path:'scratch/rm-top-sales/desktop.png'});
    await page.locator('.rm-v2-month-chart g[role=button]').filter({hasText:'Sep'}).click();
    await page.waitForFunction(()=>document.querySelector('.rm-v2-toolbar small')?.textContent.includes('September'));
    await page.waitForFunction(()=>document.querySelector('.rm-v2 [data-top-sales=customers] tbody')?.textContent.includes('2.40 L'));
    assert.notDeepEqual(await values(),yearly);
    await page.locator('.rm-v2-week-chart g[role=button]').nth(1).click();
    await page.waitForFunction(()=>document.querySelector('.rm-v2-toolbar small')?.textContent.includes('Week 2'));
    await page.waitForFunction(()=>document.querySelector('.rm-v2 [data-top-sales=customers] tbody')?.textContent.includes('60,000'));
    const weekly=await values();
    await page.getByRole('button',{name:'Download PDF',exact:true}).click();
    await page.locator('[data-pagination-ready=true]').waitFor();
    const pdfCards=page.locator('[data-rm-report-page] [data-top-sales]');
    assert.deepEqual(await pdfCards.evaluateAll(elements=>elements.map(el=>[...el.querySelectorAll('tbody tr')].map(row=>row.textContent))),weekly);
    const topBlock=page.locator('[data-rm-report-page] [data-pdf-block=top-sales]');
    assert.equal(await topBlock.count(),1);
    assert.ok(await topBlock.evaluate(el=>el.getBoundingClientRect().height<700));
    await topBlock.screenshot({path:'scratch/rm-top-sales/pdf-cards.png'});
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('dialog').getByRole('button',{name:'Download PDF',exact:true}).click();
    const download=await downloadPromise;const path='scratch/rm-top-sales/report.pdf';await download.saveAs(path);
    assert.equal(readFileSync(path).subarray(0,4).toString(),'%PDF');
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    const mobile=await cards.evaluateAll(elements=>elements.map(el=>{const r=el.getBoundingClientRect();return {left:r.left,top:r.top,bottom:r.bottom,right:r.right}}));
    assert.equal(mobile[0].left,mobile[1].left);assert.ok(mobile[1].top>=mobile[0].bottom);assert.ok(mobile.every(r=>r.right<=390));
    await page.locator('.rm-v2 [data-report-section=top-sales]').screenshot({path:'scratch/rm-top-sales/mobile.png'});
    await page.getByRole('button',{name:'Download PDF',exact:true}).click();
    await page.locator('[data-pagination-ready=true]').waitFor();
    const mobilePdf=await page.locator('[data-rm-report-page] [data-top-sales]').evaluateAll(elements=>elements.map(el=>{const r=el.getBoundingClientRect();return {top:r.top,left:r.left}}));
    assert.equal(mobilePdf[0].top,mobilePdf[1].top);assert.ok(mobilePdf[1].left>mobilePdf[0].left,'PDF remains two columns on mobile.');
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
    await page.getByLabel('Financial Year',{exact:true}).selectOption('2023-24');
    await cards.first().getByText(/Data Not Available/).waitFor();assert.equal(await cards.locator('tbody tr').count(),0);
    await page.getByRole('button',{name:'Start Preview',exact:true}).click();
    await cards.nth(1).getByText('Acid Zinc Brightener',{exact:true}).waitFor();
    assert.equal(await cards.nth(1).locator('tbody tr').count(),5);
    assert.equal(await cards.first().locator('tbody tr').count(),5);
    await cards.first().getByText('Sample Customer 1',{exact:true}).waitFor();
    await cards.nth(1).getByText(/Sample products.*illustrative sales and shares/).waitFor();
    const samples=await cards.nth(1).locator('tbody').innerText();
    await page.getByRole('button',{name:'Download PDF',exact:true}).click();
    await page.locator('[data-pagination-ready=true]').waitFor();
    assert.equal(await page.locator('[data-rm-report-page] [data-top-sales=products] tbody').innerText(),samples);
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).click();
    await page.getByRole('button',{name:'Exit Preview',exact:true}).click();
    await cards.nth(1).getByText(/Data Not Available/).waitFor();
    assert.deepEqual(errors,[]);
  } finally {await browser.close();}
});
